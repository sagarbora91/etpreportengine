using System.Text.Json;
using System.Text.Json.Serialization;
using Etp.Reporting.Application.HealthCheck;
using Microsoft.Data.SqlClient;

namespace Etp.Reporting.Infrastructure.SqlServer.HealthCheck;

/// <summary>One line of <c>ExpectedRolePermissions.json</c> (design 5.5).</summary>
public sealed record ExpectedRolePermission(
    [property: JsonPropertyName("role")] string Role,
    [property: JsonPropertyName("class")] string ClassDesc,
    [property: JsonPropertyName("schema")] string? Schema,
    [property: JsonPropertyName("object")] string? Object,
    [property: JsonPropertyName("permission")] string Permission,
    [property: JsonPropertyName("state")] string State,
    [property: JsonPropertyName("decision"), JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)] string? Decision = null,
    [property: JsonPropertyName("expect"), JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)] string? Expect = null)
{
    /// <summary>"absent": this permission must not exist (a decision the migrations alone do not show).</summary>
    [JsonIgnore]
    public bool MustBeAbsent => string.Equals(Expect, "absent", StringComparison.OrdinalIgnoreCase);

    [JsonIgnore]
    public RolePermissionKey Key => new(Role, ClassDesc, Schema, Object, Permission, State);
}

/// <summary>
/// The comparison key of a permission. Case-insensitive like the database's catalog names; column-level grants
/// collapse into their object (the procedure does not return the column).
/// </summary>
public readonly record struct RolePermissionKey(string Role, string ClassDesc, string? Schema, string? Object, string Permission, string State)
{
    public static RolePermissionKey From(RolePermission permission) =>
        new(permission.RoleName, permission.ClassDesc, permission.SchemaName, permission.ObjectName, permission.Permission, permission.State);

    public bool Equals(RolePermissionKey other) =>
        Same(Role, other.Role) && Same(ClassDesc, other.ClassDesc) && Same(Schema, other.Schema) && Same(Object, other.Object)
        && Same(Permission, other.Permission) && Same(State, other.State);

    public override int GetHashCode() => HashCode.Combine(
        Hash(Role), Hash(ClassDesc), Hash(Schema), Hash(Object), Hash(Permission), Hash(State));

    /// <summary>Sort key used by the generator, so the file diffs line by line.</summary>
    public string SortKey => string.Join('|', Role, ClassDesc, Schema ?? "", Object ?? "", Permission, State).ToLowerInvariant();

    private static bool Same(string? left, string? right) => string.Equals(left, right, StringComparison.OrdinalIgnoreCase);

    private static int Hash(string? value) => value is null ? 0 : StringComparer.OrdinalIgnoreCase.GetHashCode(value);
}

/// <summary>
/// <c>ExpectedRolePermissions.json</c>, embedded in this assembly (design 5.5, Q16). Generated by
/// <c>ExpectedRolePermissionsTests</c> from a fresh database with every migration applied; entries with a decision are
/// kept by hand. The integration test fails on any difference, so a grant change in a migration is seen.
/// </summary>
public sealed class ExpectedRolePermissionMatrix
{
    public const string ResourceName = "Etp.Reporting.Infrastructure.SqlServer.HealthCheck.ExpectedRolePermissions.json";

    public static readonly IReadOnlyList<string> Roles = ["etp_owner", "etp_store_manager", "etp_viewer", "etp_automation"];

    private static readonly JsonSerializerOptions Json = new() { PropertyNameCaseInsensitive = true, ReadCommentHandling = JsonCommentHandling.Skip };

    public ExpectedRolePermissionMatrix(IReadOnlyList<ExpectedRolePermission> entries)
    {
        Entries = entries;
        Expected = entries.Where(entry => !entry.MustBeAbsent).Select(entry => entry.Key).ToHashSet();
        Absent = entries.Where(entry => entry.MustBeAbsent).ToArray();
    }

    public IReadOnlyList<ExpectedRolePermission> Entries { get; }

    /// <summary>Every permission that must exist.</summary>
    public IReadOnlySet<RolePermissionKey> Expected { get; }

    /// <summary>Decision entries that must not exist.</summary>
    public IReadOnlyList<ExpectedRolePermission> Absent { get; }

    public static ExpectedRolePermissionMatrix Parse(string json)
    {
        ArgumentNullException.ThrowIfNull(json);
        var document = JsonSerializer.Deserialize<MatrixFile>(json, Json) ?? throw new InvalidDataException("The expected permission matrix is empty.");
        if (document.Format != 1) throw new InvalidDataException("Unknown expected permission matrix format.");
        return new ExpectedRolePermissionMatrix(document.Permissions ?? []);
    }

    /// <summary>Null when the resource is not in the assembly (a packaging fault; SEC-01 then fails).</summary>
    public static ExpectedRolePermissionMatrix? LoadEmbedded()
    {
        using var stream = typeof(ExpectedRolePermissionMatrix).Assembly.GetManifestResourceStream(ResourceName);
        if (stream is null) return null;
        using var reader = new StreamReader(stream);
        return Parse(reader.ReadToEnd());
    }

    /// <summary>
    /// The file text for <paramref name="actual"/>: one line per permission in sort order, the decision tags of
    /// <paramref name="previous"/> carried over, and its "absent" entries kept as they are.
    /// </summary>
    public static string Generate(IEnumerable<RolePermission> actual, ExpectedRolePermissionMatrix? previous)
    {
        var tags = previous?.Entries.Where(entry => !entry.MustBeAbsent && entry.Decision is not null)
            .GroupBy(entry => entry.Key).ToDictionary(group => group.Key, group => group.First().Decision)
            ?? new Dictionary<RolePermissionKey, string?>();
        var entries = Sorted(actual.Select(RolePermissionKey.From).Distinct())
            .Select(key => new ExpectedRolePermission(key.Role, key.ClassDesc, key.Schema, key.Object, key.Permission, key.State,
                tags.TryGetValue(key, out var decision) ? decision : null))
            .Concat(previous?.Absent ?? [])
            .ToArray();
        var line = new JsonSerializerOptions { Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping };
        var lines = entries.Select(entry => "    " + JsonSerializer.Serialize(entry, line)
            .Replace("\":", "\": ", StringComparison.Ordinal).Replace(",\"", ", \"", StringComparison.Ordinal));
        return "{\n  \"format\": 1,\n  \"note\": \"" + Note + "\",\n  \"permissions\": [\n"
            + string.Join(",\n", lines) + "\n  ]\n}\n";
    }

    /// <summary>Field by field, ordinal: the order of the file.</summary>
    public static IEnumerable<RolePermissionKey> Sorted(IEnumerable<RolePermissionKey> keys) =>
        keys.OrderBy(key => key.Role, StringComparer.Ordinal)
            .ThenBy(key => key.ClassDesc, StringComparer.Ordinal)
            .ThenBy(key => key.Schema ?? "", StringComparer.Ordinal)
            .ThenBy(key => key.Object ?? "", StringComparer.Ordinal)
            .ThenBy(key => key.Permission, StringComparer.Ordinal)
            .ThenBy(key => key.State, StringComparer.Ordinal);

    private const string Note =
        "Expected permissions of the four etp roles after every migration (design 5.5). Regenerate with ExpectedRolePermissionsTests (set ETP_REGENERATE_EXPECTED_PERMISSIONS=1); entries with a decision are kept by hand. expect absent = must not exist.";

    private sealed class MatrixFile
    {
        [JsonPropertyName("format")] public int Format { get; set; }
        [JsonPropertyName("permissions")] public List<ExpectedRolePermission>? Permissions { get; set; }
    }
}

/// <summary>
/// SEC-01..03 (design 5.2) from one call of <c>diag.load_role_permissions</c> (<see cref="IHealthCheckStore.LoadRolePermissionsAsync"/>).
/// Lines and sub-results carry role, schema, object and permission names and counts only, never an account name
/// (the screen reads the memberships itself for the Owner).
/// </summary>
public sealed class SecurityProbes : IHealthProbe
{
    /// <summary>Write and code rights that a non-Owner role must never gain without the matrix saying so (Fail).</summary>
    private static readonly HashSet<string> UnsafePermissions = new(StringComparer.OrdinalIgnoreCase)
    {
        "INSERT", "UPDATE", "DELETE", "EXECUTE", "ALTER", "CONTROL", "TAKE OWNERSHIP", "IMPERSONATE", "REFERENCES"
    };

    private static readonly IReadOnlyDictionary<string, string> RoleCodes = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
    {
        ["etp_owner"] = "OWNER",
        ["etp_store_manager"] = "STORE_MANAGER",
        ["etp_viewer"] = "VIEWER"
    };

    private readonly IHealthCheckStore store;
    private readonly Func<ExpectedRolePermissionMatrix?> matrix;
    private readonly string? automationPrincipal;

    /// <param name="automationPrincipal">The automation account from <c>operations.json</c>, or null when none is configured.</param>
    public SecurityProbes(IHealthCheckStore store, string? automationPrincipal, Func<ExpectedRolePermissionMatrix?>? matrix = null)
    {
        this.store = store ?? throw new ArgumentNullException(nameof(store));
        this.automationPrincipal = string.IsNullOrWhiteSpace(automationPrincipal) ? null : automationPrincipal.Trim();
        this.matrix = matrix ?? ExpectedRolePermissionMatrix.LoadEmbedded;
    }

    public IReadOnlyList<string> CheckIds { get; } = [HealthCheckId.Sec01, HealthCheckId.Sec02, HealthCheckId.Sec03];

    public async Task<IReadOnlyList<HealthCheckResult>> RunAsync(HealthCheckContext context, CancellationToken cancellationToken)
    {
        if (context.Items.TryGetValue(HealthCheckRunner.DatabaseUnreachableItem, out var unreachable) && unreachable is true)
            return CheckIds.Select(id => DatabaseProbes.Line(id, HealthOutcome.Skipped, HealthCheckTexts.DatabaseUnreachable, HealthCheckTexts.SkippedDatabaseUnreachable, null, TimeSpan.Zero)).ToArray();

        var started = System.Diagnostics.Stopwatch.StartNew();
        RolePermissionSnapshot snapshot;
        try
        {
            snapshot = await store.LoadRolePermissionsAsync(cancellationToken).ConfigureAwait(false);
        }
        catch (SqlException exception) when (DatabaseProbeSql.IsNotPermitted(exception))
        {
            return CheckIds.Select(id => DatabaseProbes.Line(id, HealthOutcome.Skipped, HealthCheckTexts.NotPermitted, HealthCheckTexts.SkippedNotPermitted, null, started.Elapsed)).ToArray();
        }
        var share = started.Elapsed / 3;
        return
        [
            EvaluatePermissions(snapshot.Permissions, matrix()) with { Duration = share },
            EvaluateMemberships(snapshot.Memberships, automationPrincipal) with { Duration = share },
            EvaluateGrantOption(snapshot.OwnersWithoutGrantOptionCount) with { Duration = share }
        ];
    }

    // ---- SEC-01 --------------------------------------------------------------------------------------------

    /// <summary>
    /// Fail: a decision entry that must be absent exists; an extra GRANT of a write or code right to etp_store_manager,
    /// etp_viewer or etp_automation; or a missing DENY. Warning: a missing GRANT (a feature refuses with 229), an extra
    /// DENY, or any other extra permission. GRANT and GRANT_WITH_GRANT_OPTION are different permissions.
    /// </summary>
    public static HealthCheckResult EvaluatePermissions(IReadOnlyList<RolePermission> actual, ExpectedRolePermissionMatrix? expected)
    {
        if (expected is null)
            return DatabaseProbes.Line(HealthCheckId.Sec01, HealthOutcome.Fail, "MATRIX_MISSING", HealthCheckTexts.SecMatrixMissingResource, null, TimeSpan.Zero);

        var actualKeys = actual.Select(RolePermissionKey.From).ToHashSet();
        var decisions = expected.Absent.Where(entry => actualKeys.Contains(entry.Key)).ToArray();
        var decisionKeys = decisions.Select(entry => entry.Key).ToHashSet();
        var extra = actualKeys.Where(key => !expected.Expected.Contains(key) && !decisionKeys.Contains(key)).OrderBy(key => key.SortKey, StringComparer.Ordinal).ToArray();
        var missing = expected.Expected.Where(key => !actualKeys.Contains(key)).OrderBy(key => key.SortKey, StringComparer.Ordinal).ToArray();

        var unsafeExtra = extra.Where(IsUnsafeExtra).ToArray();
        var missingDeny = missing.Where(key => IsDeny(key.State)).ToArray();
        var missingGrant = missing.Where(key => !IsDeny(key.State)).ToArray();
        var otherExtra = extra.Except(unsafeExtra).ToArray();

        var subs = new List<HealthCheckSubResult>();
        subs.AddRange(decisions.Select(entry => Sub(entry.Key, HealthOutcome.Fail, "DECISION_VIOLATED", entry.Decision)));
        subs.AddRange(unsafeExtra.Select(key => Sub(key, HealthOutcome.Fail, "EXTRA_GRANT")));
        subs.AddRange(missingDeny.Select(key => Sub(key, HealthOutcome.Fail, "MISSING_DENY")));
        subs.AddRange(missingGrant.Select(key => Sub(key, HealthOutcome.Warning, "MISSING_GRANT")));
        subs.AddRange(otherExtra.Select(key => Sub(key, HealthOutcome.Warning, IsDeny(key.State) ? "EXTRA_DENY" : "EXTRA_PERMISSION")));
        var detail = subs.Count > 0 ? subs : null;
        decimal differences = decisions.Length + extra.Length + missing.Length;

        if (decisions.Length > 0)
        {
            var first = decisions[0];
            return DatabaseProbes.Line(HealthCheckId.Sec01, HealthOutcome.Fail, "DECISION_VIOLATED",
                HealthCheckTexts.SecDecisionViolated(first.Decision ?? "?", Describe(first.Key)), null, TimeSpan.Zero, differences, detail);
        }
        if (unsafeExtra.Length > 0 || missingDeny.Length > 0)
        {
            var first = unsafeExtra.Length > 0 ? unsafeExtra[0] : missingDeny[0];
            return DatabaseProbes.Line(HealthCheckId.Sec01, HealthOutcome.Fail, unsafeExtra.Length > 0 ? "EXTRA_GRANT" : "MISSING_DENY",
                HealthCheckTexts.SecMatrixUnsafe(unsafeExtra.Length + missingDeny.Length, (unsafeExtra.Length > 0 ? "" : "missing ") + Describe(first)),
                null, TimeSpan.Zero, differences, detail);
        }
        if (missingGrant.Length > 0)
            return DatabaseProbes.Line(HealthCheckId.Sec01, HealthOutcome.Warning, "MISSING_GRANT",
                HealthCheckTexts.SecMatrixMissing(missingGrant.Length, Describe(missingGrant[0])), null, TimeSpan.Zero, differences, detail);
        if (otherExtra.Length > 0)
            return DatabaseProbes.Line(HealthCheckId.Sec01, HealthOutcome.Warning, IsDeny(otherExtra[0].State) ? "EXTRA_DENY" : "EXTRA_PERMISSION",
                HealthCheckTexts.SecMatrixOther(otherExtra.Length, Describe(otherExtra[0])), null, TimeSpan.Zero, differences, detail);
        return DatabaseProbes.Line(HealthCheckId.Sec01, HealthOutcome.Pass, HealthCheckTexts.Ok,
            HealthCheckTexts.SecMatrixOk(expected.Expected.Count), null, TimeSpan.Zero, 0m);
    }

    private static bool IsDeny(string state) => string.Equals(state, "DENY", StringComparison.OrdinalIgnoreCase);

    private static bool IsUnsafeExtra(RolePermissionKey key) =>
        !string.Equals(key.Role, "etp_owner", StringComparison.OrdinalIgnoreCase)
        && !IsDeny(key.State)
        && (UnsafePermissions.Contains(key.Permission)
            || key.Permission.StartsWith("ALTER", StringComparison.OrdinalIgnoreCase)
            || key.Permission.StartsWith("CREATE", StringComparison.OrdinalIgnoreCase));

    private static string Describe(RolePermissionKey key) =>
        HealthCheckTexts.SecPermission(key.Role, key.State, key.Permission, key.Schema, key.Object, key.ClassDesc);

    private static HealthCheckSubResult Sub(RolePermissionKey key, HealthOutcome outcome, string findingCode, string? decision = null)
    {
        var fields = new Dictionary<string, string>
        {
            ["role"] = HealthCheckTexts.Token(key.Role),
            ["object"] = HealthCheckTexts.Token(key.Object is null ? key.Schema ?? key.ClassDesc : (key.Schema ?? "?") + "." + key.Object),
            ["permission"] = HealthCheckTexts.Token(key.Permission),
            ["state"] = HealthCheckTexts.Token(key.State)
        };
        if (decision is not null) fields["decision"] = HealthCheckTexts.Token(decision);
        return new HealthCheckSubResult(
            HealthCheckTexts.Token(key.Role) + ":" + fields["object"] + ":" + fields["permission"], outcome, findingCode, null, fields);
    }

    // ---- SEC-02 --------------------------------------------------------------------------------------------

    /// <summary>
    /// Fail: no active Owner in etp_owner; a member of etp_owner or etp_store_manager that is not an active ETP user with
    /// that role. Warning: the same for etp_viewer or etp_automation; the configured automation account outside
    /// etp_automation or etp_store_manager. Member names are compared but never written into the line.
    /// </summary>
    public static HealthCheckResult EvaluateMemberships(IReadOnlyList<RoleMembership> memberships, string? automationPrincipal)
    {
        var subs = new List<HealthCheckSubResult>();
        var failCode = (string?)null;
        var failText = (string?)null;
        var warnCode = (string?)null;
        var warnText = (string?)null;

        foreach (var group in memberships.GroupBy(row => row.RoleName, StringComparer.OrdinalIgnoreCase).OrderBy(group => group.Key, StringComparer.Ordinal))
        {
            var role = group.Key;
            RoleCodes.TryGetValue(role, out var expectedCode);
            var wrong = group.Where(row => !row.IsActiveApplicationUser
                    || expectedCode is not null && !string.Equals(row.ApplicationRoleCode, expectedCode, StringComparison.OrdinalIgnoreCase))
                .Sum(row => Math.Max(1, row.MemberCount));
            var total = group.Sum(row => Math.Max(0, row.MemberCount));
            var serious = string.Equals(role, "etp_owner", StringComparison.OrdinalIgnoreCase) || string.Equals(role, "etp_store_manager", StringComparison.OrdinalIgnoreCase);
            var outcome = wrong == 0 ? HealthOutcome.Pass : serious ? HealthOutcome.Fail : HealthOutcome.Warning;
            subs.Add(new HealthCheckSubResult(HealthCheckTexts.Token(role), outcome, wrong == 0 ? null : "MEMBER_NOT_APP_USER", total,
                new Dictionary<string, string> { ["notActiveUsers"] = HealthCheckTexts.Count(wrong) }));
            if (wrong > 0 && serious) { failCode ??= "MEMBER_NOT_APP_USER"; failText ??= HealthCheckTexts.SecMemberNotUser(role, wrong); }
            else if (wrong > 0) { warnCode ??= "MEMBER_NOT_APP_USER"; warnText ??= HealthCheckTexts.SecMemberNotUser(role, wrong); }
        }

        var activeOwners = memberships
            .Where(row => string.Equals(row.RoleName, "etp_owner", StringComparison.OrdinalIgnoreCase) && row.IsActiveApplicationUser
                && string.Equals(row.ApplicationRoleCode, "OWNER", StringComparison.OrdinalIgnoreCase))
            .Sum(row => Math.Max(0, row.MemberCount));
        if (activeOwners == 0)
        {
            subs.Insert(0, new HealthCheckSubResult("ACTIVE_OWNER", HealthOutcome.Fail, "NO_ACTIVE_OWNER", 0));
            failCode = "NO_ACTIVE_OWNER";
            failText = HealthCheckTexts.SecNoActiveOwner;
        }

        if (automationPrincipal is { } configured)
        {
            var namesVisible = memberships.Any(row => row.MemberName is not null);
            bool InRole(string role) => memberships.Any(row => string.Equals(row.RoleName, role, StringComparison.OrdinalIgnoreCase)
                && (namesVisible ? SameAccount(row.MemberName, configured) : row.MemberCount > 0));
            if (!InRole("etp_automation"))
            {
                subs.Add(new HealthCheckSubResult("AUTOMATION_ROLE", HealthOutcome.Warning, "AUTOMATION_NOT_IN_ROLE"));
                warnCode ??= "AUTOMATION_NOT_IN_ROLE";
                warnText ??= HealthCheckTexts.SecAutomationNotInRole;
            }
            if (namesVisible && !InRole("etp_store_manager"))
            {
                subs.Add(new HealthCheckSubResult("AUTOMATION_STORE_MANAGER", HealthOutcome.Warning, "AUTOMATION_NOT_STORE_MANAGER"));
                warnCode ??= "AUTOMATION_NOT_STORE_MANAGER";
                warnText ??= HealthCheckTexts.SecAutomationNotStoreManager;
            }
        }

        if (failCode is not null)
            return DatabaseProbes.Line(HealthCheckId.Sec02, HealthOutcome.Fail, failCode, failText!, "users", TimeSpan.Zero, activeOwners, subs);
        if (warnCode is not null)
            return DatabaseProbes.Line(HealthCheckId.Sec02, HealthOutcome.Warning, warnCode, warnText!, "users", TimeSpan.Zero, activeOwners, subs);
        return DatabaseProbes.Line(HealthCheckId.Sec02, HealthOutcome.Pass, HealthCheckTexts.Ok, HealthCheckTexts.SecMembershipOk(activeOwners), null, TimeSpan.Zero, activeOwners, subs);
    }

    /// <summary>A database user named for a Windows login is <c>DOMAIN\name</c>; operations.json may hold either form.</summary>
    internal static bool SameAccount(string? memberName, string configured)
    {
        if (memberName is null) return false;
        if (string.Equals(memberName, configured, StringComparison.OrdinalIgnoreCase)) return true;
        static string Bare(string value) => value[(value.LastIndexOf('\\') + 1)..];
        return memberName.Contains('\\') != configured.Contains('\\')
            && string.Equals(Bare(memberName), Bare(configured), StringComparison.OrdinalIgnoreCase);
    }

    // ---- SEC-03 --------------------------------------------------------------------------------------------

    public static HealthCheckResult EvaluateGrantOption(int ownersWithoutGrantOption) =>
        ownersWithoutGrantOption > 0
            ? DatabaseProbes.Line(HealthCheckId.Sec03, HealthOutcome.Warning, "OWNER_NO_GRANT_OPTION",
                HealthCheckTexts.SecOwnersWithoutGrantOption(ownersWithoutGrantOption), "users", TimeSpan.Zero, ownersWithoutGrantOption)
            : DatabaseProbes.Line(HealthCheckId.Sec03, HealthOutcome.Pass, HealthCheckTexts.Ok, HealthCheckTexts.SecGrantOptionOk, null, TimeSpan.Zero, 0m);
}
